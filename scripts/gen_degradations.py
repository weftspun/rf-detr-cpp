def render():
    lines = ['', '    def Scope "Secondary"', '    {']
    lines.append('        custom string note = "Every opset-17 operator the target does not '
                 'implement, with either a rewrite into ones it does or a reason there is '
                 'none. Both are entries: an operator with no row would be indistinguishable '
                 'from one nobody has examined."')
    lines.append('')
    by_cat = {}
    for op in sorted(REWRITES):
        by_cat.setdefault(CATEGORY.get(op, "uncategorised"), []).append(op)

    for cat in sorted(by_cat):
        scope = "".join(w.capitalize() for w in cat.split("-"))
        lines += ['        def Scope "%s"' % scope, '        {']
        if cat == "trigonometric-approximate":
            lines.append('            custom string warning = "APPROXIMATE, and RANGE '
                         'LIMITED. These are polynomials, not identities, so they are absent '
                         "from RfdetrProofs/Secondary.lean on purpose -- a theorem claiming "
                         'equality would be false. Worse, they hold only on [-pi/2, pi/2]. '
                         'Reviewed against tinygrad codegen/decomp/transcendental.py (MIT), '
                         'itself derived from SLEEF: the POLYNOMIAL is plain multiply-add and '
                         'emits fine, but the Payne-Hanek and Cody-Waite range reductions that '
                         'make it valid everywhere rest on bitcast, shifts, frexp, ldexp and '
                         'round-to-int -- 31 casts and 6 bitcasts in that file -- and every '
                         'one of those is in Refused. So a correct sine over the reals is not '
                         'reachable on this target, and an argument outside the interval '
                         'returns a wrong number rather than an error."')
        for op in by_cat[cat]:
            identity, uses = REWRITES[op]
            seq = ", ".join('"%s"' % u for u in uses)
            lines += [
                '            def Scope "%s"' % op,
                '            {',
                '                custom string identity = "%s"' % identity.replace('"', "'"),
                '                custom token[] sequence = [%s]' % seq,
            ]
            if op in PROOF:
                lines.append('                custom token proof = "%s"' % PROOF[op])
            if op in SPEC_BODY:
                lines.append('                custom token spec_body = "%s"' % SPEC_BODY[op])
                lines.append('                custom string source = "ONNX spec FunctionProto, '
                             'Apache-2.0 -- authoritative, and it disagrees with the '
                             'hand-written identity in at least one place: the spec builds '
                             'GreaterOrEqual from Equal, Greater and Or where this table had '
                             '1 - Less. Both compute it; only one is the specification."')
            lines += [
                '            }',
                '',
            ]
        lines += ['        }', '']
    lines += ['    }', '', '    def Scope "Refused"', '    {']
    lines.append('        custom string note = "No rewrite, and the category says how '
                 'permanent that is. A data-dependent shape can never be a static graph; a '
                 'rounding refusal is a measurement that could be revisited on a wider '
                 'datapath."')
    lines.append('')
    for op in sorted(REFUSED):
        category, why = REFUSED[op]
        lines += [
            '        def Scope "%s"' % op,
            '        {',
            '            custom token category = "%s"' % category,
            '            custom string reason = "%s"' % why.replace('"', "'"),
            '        }',
            '',
        ]
    lines += ['    }', '']
    return "\n".join(lines)


def main(argv):
    body = render()
    if "--print" in argv:
        print(body)
        return 0

    path = HERE / "hailo_ops.usda"
    text = path.read_text(encoding="utf-8")
    # Drop any existing Secondary/Refused scopes, then append the freshly rendered ones.
    text = re.sub(r'\n    def Scope "(?:Secondary|Refused)"\n    \{.*?\n    \}\n',
                  "\n", text, flags=re.S)
    text = text.rstrip().rstrip("}").rstrip() + "\n" + body + "}\n"
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %d rewrites and %d refusals (%d operators)"
          % (len(REWRITES), len(REFUSED), len(REWRITES) + len(REFUSED)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
