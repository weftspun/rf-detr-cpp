#!/usr/bin/env python3
"""Generate the degradation table in `hailo_ops.usda`.

Every opset-17 operator the target does not implement is here, with either a rewrite into
operators it does implement, or a reason there is none. Both are entries. An operator with no
row at all would be indistinguishable from one nobody has looked at, and that ambiguity is the
thing this file exists to remove.

THE PRIMITIVES A REWRITE MAY USE are exactly the documented set -- `Layers` plus `Activations`
plus anything reachable through a `Patterns` sequence -- and nothing else. A rewrite naming an
operator that is itself unsupported and has no rewrite of its own is a rewrite that bottoms out
in nothing; `check_device_ops.py` rejects those, so the table cannot quietly rest on air.

WHY SOME HAVE NO REWRITE, and the categories are worth separating because they are not equally
permanent:

    data-dependent-shape  the output shape depends on the values, which a static dataflow
                          graph cannot express at all. Compress, NonZero, Unique.
    control-flow          If, Loop, Scan: execution that branches at runtime.
    not-a-tensor          sequence and optional types. The CONTAINER is not a tensor even
                          where its elements are, which is what the category is about.
    not-reproducible      the result depends on the environment rather than only on the
                          input, so two machines running the same graph disagree. Text
                          preprocessing belongs in a tokenizer, ahead of the graph, and the
                          ONNX ecosystem puts it in a custom-op domain that no accelerator
                          toolchain lowers.
    nondeterministic      the random family. A rewrite would have to invent an RNG, and a
                          corpus generated by one is not reproducible.
    toolchain-owns-it     the quantization operators. The compiler quantizes; emitting
                          QuantizeLinear ourselves would fight it for the same job.
    rounding              Floor, Ceil, Round, Mod. A rewrite exists on paper -- a sum of
                          clipped steps -- and `native_onehot.py` measured that family dying
                          under int8, where the amplification a step needs is exactly what
                          quantization destroys. Recorded as refused rather than absent.

Usage:
    python scripts/gen_degradations.py           # rewrite the Secondary scope in place
    python scripts/gen_degradations.py --print   # show what it would write
"""
